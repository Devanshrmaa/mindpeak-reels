#!/usr/bin/env node
/**
 * gen-freshness-data.mjs
 *
 * Captures honest, git-derived last-modification timestamps for content
 * source files and writes them to src/lib/freshnessData.generated.ts.
 * Also emits seo-reports/stale-content.json flagging files that reference
 * past exam years or haven't been touched in months.
 *
 * Runs at build time (npm run build). Idempotent: if git state hasn't
 * changed, output is identical and no false freshness signal is emitted.
 *
 * Design principle: this script never invents dates. Every date it emits
 * is the actual `git log -1 --format=%cI <file>` output. If a file has
 * no git history (e.g. uncommitted), it is omitted, not faked.
 */

import { execSync } from 'node:child_process';
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs';
import { dirname } from 'node:path';

/* ── Content source files. These drive what appears on real pages.
       Adding files here = those pages' freshness is tracked. ── */
const SOURCES = [
  'src/data/blogData.ts',
  'src/data/chapterData.ts',
  'src/data/seoPageData.ts',
  'src/data/stateLandingPages.ts',
  'src/data/cityData.ts',
  'src/data/cityUniqueContent.ts',
  'src/data/examInfoData.ts',
  'src/data/differenceBetweenData.ts',
  'src/data/counsellingData.ts',
  'src/data/formulaSheetData.ts',
  'src/data/comparisonData.ts',
  'src/data/coursesData.ts',
  'src/lib/programmaticBlogs.ts',
  'src/lib/examEventBlogs.ts',
];

function gitDateOf(file) {
  try {
    const out = execSync(`git log -1 --format=%cI -- ${file}`, {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    return out || null;
  } catch {
    return null;
  }
}

/* ── Collect honest dates. Skip files git knows nothing about. ── */
const sourceDates = {};
for (const f of SOURCES) {
  const iso = gitDateOf(f);
  if (iso) sourceDates[f] = iso.split('T')[0];
}

/* ── Build base date = most recent content commit across all sources.
       Used as a fallback when a slug doesn't map to a specific source. ── */
const allDates = Object.values(sourceDates).sort();
const buildBaseDate = allDates[allDates.length - 1] || null;

if (!buildBaseDate) {
  console.error('[gen-freshness-data] No git dates resolved. Refusing to fake a date.');
  process.exit(1);
}

/* ── Detect outdated year references. We use a conservative window:
       flag mentions of (currentYear - 2) or earlier as "potentially outdated"
       since recent-past years (e.g. last year's paper analysis) are valid
       historical content. ── */
const CURRENT_YEAR = new Date().getFullYear();
const OUTDATED_YEARS = [CURRENT_YEAR - 2, CURRENT_YEAR - 3, CURRENT_YEAR - 4];

const stalePages = [];
for (const [file, date] of Object.entries(sourceDates)) {
  if (!existsSync(file)) continue;
  const content = readFileSync(file, 'utf8');
  const yearsFound = OUTDATED_YEARS.filter((y) => new RegExp(`\\b${y}\\b`).test(content));
  const daysSince = Math.floor((Date.now() - new Date(date).getTime()) / 86_400_000);

  let status = 'fresh';
  if (daysSince > 180) status = 'stale';
  else if (daysSince > 90) status = 'aging';
  if (yearsFound.length > 0) status = 'outdated-year-ref';

  if (status === 'fresh') continue;
  stalePages.push({
    file,
    lastModified: date,
    daysSinceUpdate: daysSince,
    status,
    yearsReferenced: yearsFound,
  });
}

/* ── Emit the generated TypeScript module. Committing this file is fine —
       it's regenerated every build, so PRs that touch content also touch
       this and the diff makes the freshness change auditable. ── */
const generated = `// AUTO-GENERATED by scripts/gen-freshness-data.mjs — do not edit by hand.
// Regenerated on every \`npm run build\` from real git log timestamps.
// Editing this file directly will fake freshness signals — use a real
// content commit instead.

export const SOURCE_LAST_MODIFIED: Readonly<Record<string, string>> = ${JSON.stringify(sourceDates, null, 2)} as const;

export const BUILD_BASE_DATE = '${buildBaseDate}';
`;

const tsTarget = 'src/lib/freshnessData.generated.ts';
mkdirSync(dirname(tsTarget), { recursive: true });
writeFileSync(tsTarget, generated);

mkdirSync('seo-reports', { recursive: true });
writeFileSync(
  'seo-reports/stale-content.json',
  JSON.stringify(
    {
      generatedAt: new Date().toISOString(),
      currentYear: CURRENT_YEAR,
      buildBaseDate,
      totalSources: Object.keys(sourceDates).length,
      flaggedCount: stalePages.length,
      stalePages,
    },
    null,
    2,
  ),
);

console.log(
  `[gen-freshness-data] wrote ${tsTarget} (${Object.keys(sourceDates).length} sources, base ${buildBaseDate})`,
);
console.log(
  `[gen-freshness-data] wrote seo-reports/stale-content.json (${stalePages.length} flagged for review)`,
);
