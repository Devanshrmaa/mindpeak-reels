/**
 * generate-topic-sitemap.mjs
 * Run: node scripts/generate-topic-sitemap.mjs
 * Generates public/sitemap-topics.xml with all 1,184 topic URLs
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

function topicToSlug(topic) {
  return topic
    .toLowerCase()
    .replace(/['']/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

// Parse chapter data files to extract slug + topics
const files = [
  'jeePhysics', 'jeeChemistry', 'jeeMaths',
  'neetBiology', 'neetPhysics', 'neetChemistry',
];

const topicUrls = [];

for (const file of files) {
  const content = readFileSync(join(ROOT, 'src/data/chapters', `${file}.ts`), 'utf-8');

  // Extract each chapter object's slug and topics
  // Match slug field
  const slugRegex = /slug:\s*'([^']+)'/g;
  const topicsRegex = /topics:\s*\[([^\]]+)\]/g;

  const slugs = [];
  let m;
  while ((m = slugRegex.exec(content)) !== null) {
    slugs.push(m[1]);
  }

  const topicsArrays = [];
  while ((m = topicsRegex.exec(content)) !== null) {
    // Extract individual topic strings (both single and double quoted)
    const raw = m[1];
    const topics = [];
    const topicRegex = /(?:'([^']*)'|"([^"]*)")/g;
    let tm;
    while ((tm = topicRegex.exec(raw)) !== null) {
      topics.push(tm[1] || tm[2]);
    }
    topicsArrays.push(topics);
  }

  for (let i = 0; i < slugs.length && i < topicsArrays.length; i++) {
    for (const topic of topicsArrays[i]) {
      topicUrls.push(`${slugs[i]}/${topicToSlug(topic)}`);
    }
  }
}

const today = new Date().toISOString().split('T')[0];

const xml = `<?xml version="1.0" encoding="UTF-8"?>

<!--
================================================================
  MINDPEAK INSTITUTE — TOPIC SITEMAP v1.0
  Auto-generated by scripts/generate-topic-sitemap.mjs
  Total topic URLs: ${topicUrls.length}
  Generated: ${today}
================================================================
-->

<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">

${topicUrls
  .map(
    (url) =>
      `<url><loc>https://mindpeakinstitute.com/${url}</loc><lastmod>${today}</lastmod><changefreq>monthly</changefreq><priority>0.55</priority></url>`
  )
  .join('\n')}

</urlset>
`;

writeFileSync(join(ROOT, 'public/sitemap-topics.xml'), xml);
console.log(`✅ Generated sitemap-topics.xml with ${topicUrls.length} topic URLs`);
